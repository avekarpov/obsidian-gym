import { DataAdapter, normalizePath } from "obsidian";
import { LightDb } from "./lightdb";
import { ExerciseNotes } from "./notes";
import { loadExercises, loadSchemes } from "./workout";

export const EXPORT_ABOUT = "Generated by the Gym plugin from the LightDB 'gym' database. Do not edit.";

const DEBOUNCE_MS = 2000;

interface SetRow {
  workout_id: string;
  exercise_id: string;
  weight_g: number;
  reps: number | null;
  skipped: number;
}

export function buildExport(db: LightDb, notes: ExerciseNotes): string {
  const exercises = loadExercises(db);
  notes.decorate(exercises);
  const schemes = loadSchemes(db);
  const schemeNames = new Map(schemes.map((s) => [s.id, s.name]));
  const kg = (grams: number | null) => (grams === null ? null : grams / 1000);

  const plan = schemes.map((scheme) => ({
    group: scheme.name,
    exercises: scheme.exercises
      .map((id) => exercises.get(id))
      .filter((e) => e !== undefined)
      .map((e) => ({ name: e.name, sets: e.sets, reps: e.reps, last_weight_kg: kg(e.weightG) })),
  }));

  const setsByWorkout = new Map<string, SetRow[]>();
  for (const row of db.all("SELECT workout_id, exercise_id, weight_g, reps, skipped FROM sets ORDER BY done_at, id")) {
    const set = row as unknown as SetRow;
    const list = setsByWorkout.get(set.workout_id) ?? [];
    list.push(set);
    setsByWorkout.set(set.workout_id, list);
  }

  const workouts = db.all("SELECT id, schemes, started_at, finished_at FROM workouts ORDER BY started_at DESC, id").map((w) => {
    const startedAt = w.started_at as string;
    const finishedAt = w.finished_at as string | null;
    const byExercise = new Map<string, { name: string; sets: { weight_kg: number; reps: number | null }[]; skipped_sets: number }>();
    for (const set of setsByWorkout.get(w.id as string) ?? []) {
      let entry = byExercise.get(set.exercise_id);
      if (!entry) {
        entry = { name: exercises.get(set.exercise_id)?.name ?? set.exercise_id, sets: [], skipped_sets: 0 };
        byExercise.set(set.exercise_id, entry);
      }
      if (set.skipped) entry.skipped_sets++;
      else entry.sets.push({ weight_kg: set.weight_g / 1000, reps: set.reps });
    }
    return {
      started_at: startedAt,
      finished_at: finishedAt,
      duration_min: finishedAt ? Math.round((Date.parse(finishedAt) - Date.parse(startedAt)) / 60000) : null,
      groups: (w.schemes as string).split(",").filter(Boolean).map((id) => schemeNames.get(id) ?? id),
      exercises: [...byExercise.values()],
    };
  });

  const latest = db.all(`SELECT max(t) AS t FROM (
    SELECT max(done_at) AS t FROM sets
    UNION ALL SELECT max(started_at) FROM workouts
    UNION ALL SELECT max(finished_at) FROM workouts)`)[0]?.t as string | null;

  return JSON.stringify({
    about: EXPORT_ABOUT,
    data_as_of: latest ?? null,
    units: { weight: "kg, total load", time: "ISO 8601 UTC" },
    plan,
    workouts,
  }, null, 2) + "\n";
}

export class LlmExporter {
  private timer: number | null = null;
  private lastPath: string | null;

  constructor(
    private adapter: DataAdapter,
    private db: LightDb,
    private notes: ExerciseNotes,
    private readPath: () => Promise<string>,
    initialPath: string,
  ) {
    this.lastPath = clean(initialPath);
  }

  schedule(): void {
    if (this.timer !== null) window.clearTimeout(this.timer);
    this.timer = window.setTimeout(() => {
      this.timer = null;
      void this.run();
    }, DEBOUNCE_MS);
  }

  cancel(): void {
    if (this.timer !== null) window.clearTimeout(this.timer);
    this.timer = null;
  }

  async run(): Promise<void> {
    try {
      const path = clean(await this.readPath());
      if (this.lastPath && this.lastPath !== path) await this.removeIfOurs(this.lastPath);
      this.lastPath = path;
      if (!path) return;

      const content = buildExport(this.db, this.notes);
      if (await this.adapter.exists(path)) {
        const current = await this.adapter.read(path);
        if (current === content) return;
        if (!isOurs(current)) {
          console.warn(`gym: ${path} is not a Gym export, not overwriting it`);
          return;
        }
      } else {
        await this.ensureFolder(path);
      }
      await this.adapter.write(path, content);
    } catch (error) {
      console.error("gym: LLM export failed", error);
    }
  }

  private async removeIfOurs(path: string): Promise<void> {
    if (!(await this.adapter.exists(path))) return;
    if (isOurs(await this.adapter.read(path))) await this.adapter.remove(path);
  }

  private async ensureFolder(path: string): Promise<void> {
    const folder = path.includes("/") ? path.slice(0, path.lastIndexOf("/")) : "";
    if (folder && !(await this.adapter.exists(folder))) await this.adapter.mkdir(folder);
  }
}

function clean(path: string | undefined | null): string | null {
  const trimmed = (path ?? "").trim();
  return trimmed ? normalizePath(trimmed) : null;
}

function isOurs(content: string): boolean {
  try {
    return (JSON.parse(content) as { about?: unknown }).about === EXPORT_ABOUT;
  } catch {
    return false;
  }
}
