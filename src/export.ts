export class LlmExporter {
  private timer: number | null = null;
  private lastDir: string | null;

  constructor(
    private adapter: DataAdapter,
    private db: LightDb,
    private notes: ExerciseNotes,
    private readDir: () => Promise<string>,
    initialDir: string,
  ) {
    this.lastDir = clean(initialDir);
  }

  schedule(): void {
    if (this.timer !== null) window.clearTimeout(this.timer);
    this.timer = window.setTimeout(() => {
      this.timer = null;
      void this.run();
    }, DEBOUNCE_MS);
  }

  cancel(): void {
    if (this.timer !== null) window.clearTimeout(this.timer);
    this.timer = null;
  }

  async run(): Promise<void> {
    try {
      const dir = clean(await this.readDir());
      if (this.lastDir && this.lastDir !== dir) await this.removeOurs(this.lastDir);
      this.lastDir = dir;
      if (!dir) return;
      if (!(await this.adapter.exists(dir))) await this.adapter.mkdir(dir);
      await this.writeIfChanged(`${dir}/${DATA_FILE}`, buildExport(this.db, this.notes), isOurData);
      await this.writeIfChanged(`${dir}/${README_FILE}`, README, isOurReadme);
    } catch (error) {
      console.error("gym: LLM export failed", error);
    }
  }

  private async writeIfChanged(path: string, content: string, ours: (text: string) => boolean): Promise<void> {
    if (await this.adapter.exists(path)) {
      const current = await this.adapter.read(path);
      if (current === content) return;
      if (!ours(current)) {
        console.warn(`gym: ${path} was not written by Gym, not overwriting it`);
        return;
      }
    }
    await this.adapter.write(path, content);
  }

  private async removeOurs(dir: string): Promise<void> {
    if (!(await this.adapter.exists(dir))) return;
    for (const [name, ours] of [[DATA_FILE, isOurData], [README_FILE, isOurReadme]] as const) {
      const path = `${dir}/${name}`;
      if ((await this.adapter.exists(path)) && ours(await this.adapter.read(path))) await this.adapter.remove(path);
    }
    const left = await this.adapter.list(dir);
    if (!left.files.length && !left.folders.length) await this.adapter.rmdir(dir, false);
  }
}

function clean(path: string | undefined | null): string | null {
  const trimmed = (path ?? "").trim();
  return trimmed ? normalizePath(trimmed) : null;
}

function isOurData(content: string): boolean {
  try {
    return (JSON.parse(content) as { about?: unknown }).about === EXPORT_ABOUT;
  } catch {
    return false;
  }
}

function isOurReadme(content: string): boolean {
  return content.startsWith(README_MARKER);
}
